//! The constraint tests the learners ask: conditional independence within a
//! distribution, and invariance across two (Thm 16.2.3, Corol. 16.2.4).

use std::collections::BTreeMap;

use super::DiscoveryError;
use super::interventional::{FNode, augment};
use crate::fairness::Dataset;
use crate::graph::dseparation::Admg;
use crate::transport::invariance::chi2_survival;

/// A conditional independence test: whether `x ⊥ y | z` in the data.
pub trait Independence {
    /// Whether `x` and `y` are independent given `z`.
    ///
    /// # Errors
    ///
    /// Whatever the test reports for an unknown variable or bad data.
    fn independent(&mut self, x: &str, y: &str, z: &[&str]) -> Result<bool, DiscoveryError>;
}

/// The tests of the interventional learners, over a tuple of distributions
/// `P_1, …, P_m` generated by soft interventions on one system.
pub trait Invariance {
    /// The number of distributions.
    fn distributions(&self) -> usize;

    /// Whether `x ⊥ y | z` in distribution `dist`.
    ///
    /// # Errors
    ///
    /// Whatever the test reports for an unknown variable or bad data.
    fn independent(
        &mut self,
        dist: usize,
        x: &str,
        y: &str,
        z: &[&str],
    ) -> Result<bool, DiscoveryError>;

    /// Whether `P_i(y | w) = P_j(y | w)`.
    ///
    /// # Errors
    ///
    /// Whatever the test reports for an unknown variable or bad data.
    fn invariant(
        &mut self,
        i: usize,
        j: usize,
        y: &str,
        w: &[&str],
    ) -> Result<bool, DiscoveryError>;
}

/// Answers independence questions by d-separation in a causal diagram:
/// FCI then returns exactly the PAG of the diagram's MAG (faithfulness).
#[derive(Clone, Debug)]
pub struct GraphOracle {
    g: Admg,
}

impl GraphOracle {
    /// The oracle of `g`, whose bidirected edges stand for latent
    /// confounders.
    #[must_use]
    pub fn new(g: Admg) -> Self {
        Self { g }
    }
}

impl Independence for GraphOracle {
    fn independent(&mut self, x: &str, y: &str, z: &[&str]) -> Result<bool, DiscoveryError> {
        Ok(self.g.is_d_separated(&[x], &[y], z)?)
    }
}

/// Answers the interventional learners' questions from a causal diagram
/// and the true targets of each distribution, by d-separation in the
/// augmented diagram (Prop. 16.2.5). Conditional independence is the same
/// in every distribution (Thm 16.2.3, rule 1). `P_i(y | w) = P_j(y | w)`
/// holds when `y` is separated from the F-node of the pair `(i, j)` given
/// `w` and every other F-node (Eq. 16.12).
#[derive(Clone, Debug)]
pub struct AugmentedOracle {
    g: Admg,
    augmented: Admg,
    fnodes: Vec<FNode>,
    m: usize,
}

impl AugmentedOracle {
    /// The oracle of `g` with distribution `k` generated by the targets
    /// `targets[k]` (entries `"X"` or `"X:2"`, see the module docs).
    ///
    /// # Errors
    ///
    /// Those of [`augment`].
    pub fn new(g: Admg, targets: &[&[&str]]) -> Result<Self, DiscoveryError> {
        let (augmented, fnodes) = augment(&g, targets, false)?;
        Ok(Self {
            g,
            augmented,
            fnodes,
            m: targets.len(),
        })
    }
}

impl Invariance for AugmentedOracle {
    fn distributions(&self) -> usize {
        self.m
    }

    fn independent(
        &mut self,
        _dist: usize,
        x: &str,
        y: &str,
        z: &[&str],
    ) -> Result<bool, DiscoveryError> {
        Ok(self.g.is_d_separated(&[x], &[y], z)?)
    }

    fn invariant(
        &mut self,
        i: usize,
        j: usize,
        y: &str,
        w: &[&str],
    ) -> Result<bool, DiscoveryError> {
        let pair = (i.min(j), i.max(j));
        let f =
            self.fnodes.iter().find(|f| f.pair == pair).ok_or_else(|| {
                DiscoveryError::InvalidInput(format!("no distributions {i} and {j}"))
            })?;
        let mut given: Vec<&str> = w.to_vec();
        given.extend(
            self.fnodes
                .iter()
                .filter(|o| o.name != f.name)
                .map(|o| o.name.as_str()),
        );
        Ok(self
            .augmented
            .is_d_separated(&[f.name.as_str()], &[y], &given)?)
    }
}

/// How [`DataTests`] decides a constraint.
#[derive(Clone, Copy, Debug, PartialEq)]
enum Mode {
    /// A G-test at significance `alpha`: the constraint holds when the test
    /// does not reject it.
    GTest(f64),
    /// Exact tables: the constraint holds when the probabilities agree
    /// within the tolerance.
    Exact(f64),
}

/// Constraint tests on data: one data set per distribution, row weights
/// read as frequencies.
#[derive(Clone, Debug)]
pub struct DataTests<'a> {
    data: Vec<&'a Dataset>,
    mode: Mode,
}

impl<'a> DataTests<'a> {
    /// G-tests (likelihood-ratio χ² tests) at significance `alpha`.
    /// Invariance `P_i(y | w) = P_j(y | w)` is tested as the independence of
    /// `y` and the data set's label given `w` in the pooled data.
    #[must_use]
    pub fn g_test(data: &[&'a Dataset], alpha: f64) -> Self {
        Self {
            data: data.to_vec(),
            mode: Mode::GTest(alpha),
        }
    }

    /// Comparisons of exact distributions (weighted tables) within
    /// `tolerance`.
    #[must_use]
    pub fn exact(data: &[&'a Dataset], tolerance: f64) -> Self {
        Self {
            data: data.to_vec(),
            mode: Mode::Exact(tolerance),
        }
    }

    fn data(&self, k: usize) -> Result<&'a Dataset, DiscoveryError> {
        self.data
            .get(k)
            .copied()
            .ok_or_else(|| DiscoveryError::InvalidInput(format!("no data set {k}")))
    }
}

/// One observation: `x`, `y`, the values of `z`, and the row's weight.
type Row = (String, String, Vec<String>, f64);

/// Weighted counts of `(x, y, z)` keys: each row contributes its weight.
type Counts = BTreeMap<(String, String, Vec<String>), f64>;

fn column<'d>(d: &'d Dataset, v: &str, r: usize) -> Result<&'d str, DiscoveryError> {
    d.value(v, r)
        .ok_or_else(|| DiscoveryError::UnknownVariable(v.to_string()))
}

fn counts(rows: &[Row]) -> Counts {
    let mut c = Counts::new();
    for (x, y, z, w) in rows {
        *c.entry((x.clone(), y.clone(), z.clone())).or_default() += w;
    }
    c
}

/// Whether `x ⊥ y | z` holds in the rows, by `mode`.
fn decide(rows: &[Row], mode: Mode) -> bool {
    let c = counts(rows);
    // Per stratum z: n(x, y), n(x), n(y), n.
    let mut strata: BTreeMap<&Vec<String>, BTreeMap<(&String, &String), f64>> = BTreeMap::new();
    for ((x, y, z), w) in &c {
        *strata.entry(z).or_default().entry((x, y)).or_default() += w;
    }
    let total: f64 = c.values().sum();
    match mode {
        Mode::GTest(alpha) => {
            let (mut g, mut df) = (0.0, 0.0);
            for cells in strata.values() {
                let n: f64 = cells.values().sum();
                let mut nx: BTreeMap<&String, f64> = BTreeMap::new();
                let mut ny: BTreeMap<&String, f64> = BTreeMap::new();
                for ((x, y), w) in cells {
                    *nx.entry(x).or_default() += w;
                    *ny.entry(y).or_default() += w;
                }
                for ((x, y), w) in cells {
                    if *w > 0.0 {
                        g += 2.0 * w * (w * n / (nx[x] * ny[y])).ln();
                    }
                }
                df += ((nx.len() as f64) - 1.0).max(0.0) * ((ny.len() as f64) - 1.0).max(0.0);
            }
            df == 0.0 || chi2_survival(g.max(0.0), df) > alpha
        }
        Mode::Exact(tol) => {
            if total <= 0.0 {
                return true;
            }
            strata.values().all(|cells| {
                let n: f64 = cells.values().sum();
                let mut nx: BTreeMap<&String, f64> = BTreeMap::new();
                let mut ny: BTreeMap<&String, f64> = BTreeMap::new();
                for ((x, y), w) in cells {
                    *nx.entry(x).or_default() += w;
                    *ny.entry(y).or_default() += w;
                }
                nx.iter().all(|(x, px)| {
                    ny.iter().all(|(y, py)| {
                        let pxy = cells.get(&(*x, *y)).copied().unwrap_or(0.0);
                        // P(x, y | z) − P(x | z) P(y | z), weighted by P(z).
                        (pxy / total - px * py / (n * total)).abs() <= tol
                    })
                })
            })
        }
    }
}

fn rows_of(
    d: &Dataset,
    x: &str,
    y: &str,
    z: &[&str],
) -> Result<Vec<Row>, DiscoveryError> {
    (0..d.len())
        .map(|r| {
            Ok((
                column(d, x, r)?.to_string(),
                column(d, y, r)?.to_string(),
                z.iter()
                    .map(|v| Ok(column(d, v, r)?.to_string()))
                    .collect::<Result<Vec<_>, DiscoveryError>>()?,
                d.weights().map_or(1.0, |w| w[r]),
            ))
        })
        .collect()
}

impl Independence for DataTests<'_> {
    fn independent(&mut self, x: &str, y: &str, z: &[&str]) -> Result<bool, DiscoveryError> {
        Invariance::independent(self, 0, x, y, z)
    }
}

impl Invariance for DataTests<'_> {
    fn distributions(&self) -> usize {
        self.data.len()
    }

    fn independent(
        &mut self,
        dist: usize,
        x: &str,
        y: &str,
        z: &[&str],
    ) -> Result<bool, DiscoveryError> {
        Ok(decide(&rows_of(self.data(dist)?, x, y, z)?, self.mode))
    }

    fn invariant(
        &mut self,
        i: usize,
        j: usize,
        y: &str,
        w: &[&str],
    ) -> Result<bool, DiscoveryError> {
        // Pool the two data sets with a label, normalizing each to total
        // weight 1 under exact comparison so their sizes do not matter.
        let mut rows = Vec::new();
        for (label, k) in [("i", i), ("j", j)] {
            let d = self.data(k)?;
            let total: f64 = (0..d.len())
                .map(|r| d.weights().map_or(1.0, |w| w[r]))
                .sum();
            for r in 0..d.len() {
                let weight = d.weights().map_or(1.0, |w| w[r]);
                rows.push((
                    label.to_string(),
                    column(d, y, r)?.to_string(),
                    w.iter()
                        .map(|v| Ok(column(d, v, r)?.to_string()))
                        .collect::<Result<Vec<_>, DiscoveryError>>()?,
                    match self.mode {
                        Mode::GTest(_) => weight,
                        Mode::Exact(_) => weight / total,
                    },
                ));
            }
        }
        Ok(match self.mode {
            Mode::GTest(_) => decide(&rows, self.mode),
            Mode::Exact(tol) => {
                // P_i(y | w) = P_j(y | w) wherever both see w.
                let c = counts(&rows);
                let mut by_w: BTreeMap<&Vec<String>, BTreeMap<&str, BTreeMap<&String, f64>>> =
                    BTreeMap::new();
                for ((label, yv, wv), p) in &c {
                    *by_w
                        .entry(wv)
                        .or_default()
                        .entry(label.as_str())
                        .or_default()
                        .entry(yv)
                        .or_default() += p;
                }
                by_w.values()
                    .all(|sides| match (sides.get("i"), sides.get("j")) {
                        (Some(a), Some(b)) => {
                            let (ta, tb): (f64, f64) = (a.values().sum(), b.values().sum());
                            a.keys().chain(b.keys()).all(|yv| {
                                let pa = a.get(yv).copied().unwrap_or(0.0) / ta;
                                let pb = b.get(yv).copied().unwrap_or(0.0) / tb;
                                (pa - pb).abs() <= tol
                            })
                        }
                        _ => true,
                    })
            }
        })
    }
}
